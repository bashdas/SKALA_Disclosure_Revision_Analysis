import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const tokenFile = process.env.E2E_TOKEN_FILE!
test.beforeEach(async ({ page }) => {
 const {token} = JSON.parse(readFileSync(tokenFile, 'utf8'))
 await page.addInitScript(t => {
  if (!sessionStorage.getItem('test-auth-seeded')) {
    sessionStorage.setItem('disclosure-check.token', t)
    sessionStorage.setItem('test-auth-seeded', '1')
  }
 }, token)
})
test('기업 상단 배치와 모달 위 상단 중앙 토스트를 확인합니다', async ({ page }) => {
 for (const width of [1720, 390]) {
  await page.setViewportSize({width,height:1000})
  await page.goto('/companies/00126478')
  const identity = page.locator('.company-market-name')
  await expect(identity).toBeVisible()
  await expect(page.locator('.company-market-panel .skeleton-state')).toHaveCount(0)
  const header = await page.locator('.company-workspace-header').boundingBox()
  const brand = await identity.boundingBox()
  expect(Math.round(brand!.y - header!.y)).toBe(width > 650 ? 72 : 48)
  const name = await page.locator('#company-title').boundingBox()
  const star = await identity.locator('.favorite-button').boundingBox()
  expect(Math.abs(name!.y+name!.height/2-star!.y-star!.height/2)).toBeLessThan(1)
  expect(await page.locator('.company-market-panel').evaluate(el=>getComputedStyle(el).borderTopWidth)).toBe('1px')
  const top = await page.locator('.company-market-identity').boundingBox()
  const panel = await page.locator('.company-market-panel').boundingBox()
  expect(panel!.y).toBeGreaterThan(top!.y + top!.height)
  const prices = await page.locator('.company-day-prices').boundingBox()
  const graph = await page.locator('.company-price-chart').boundingBox()
  expect(prices!.x).toBeGreaterThanOrEqual(graph!.x + graph!.width - 1)
  const groups = page.locator('.company-market-panel > .company-price-chart, .company-market-panel > .company-day-prices, .company-market-panel > .company-market-stats')
  await expect(groups).toHaveCount(4)
  const widths = await groups.evaluateAll(els => els.map(el => el.getBoundingClientRect().width))
  expect(Math.max(...widths) - Math.min(...widths)).toBeLessThan(2)
  expect(await groups.nth(1).evaluate(el => getComputedStyle(el).borderLeftWidth)).toBe('1px')
  expect(await groups.nth(3).evaluate(el => getComputedStyle(el).borderLeftWidth)).toBe('1px')
  if(width > 1000) expect(await groups.nth(2).evaluate(el => getComputedStyle(el).borderLeftWidth)).toBe('1px')
  if (width > 1000) {
    const graphSvg = await page.locator('.company-price-chart svg').boundingBox()
    expect(Math.abs(graphSvg!.x - panel!.x)).toBeLessThan(1)
    const lastRow = await page.locator('.company-market-stats').last().locator('div').first().boundingBox()
    expect(Math.abs(lastRow!.x + lastRow!.width - panel!.x - panel!.width + 24)).toBeLessThan(1)
    const cells = await groups.all()
    for (const cell of cells.slice(1, 3)) {
      const outer = await cell.boundingBox()
      const inner = await cell.locator('div').first().boundingBox()
      expect(Math.abs(inner!.x + inner!.width / 2 - outer!.x - outer!.width / 2)).toBeLessThan(1)
    }
    const rowWidths = await page.locator('.company-day-prices > div, .company-market-stats > div').evaluateAll(els => els.map(el => el.getBoundingClientRect().width))
    expect(Math.max(...rowWidths) - Math.min(...rowWidths)).toBeLessThan(1)
  }
  const chart = await page.locator('.company-price-chart svg').boundingBox()
  const chartPadding = await page.locator('.company-price-chart').evaluate(el => parseFloat(getComputedStyle(el).paddingRight) + parseFloat(getComputedStyle(el).paddingLeft))
  expect(Math.abs(chart!.width - graph!.width + chartPadding)).toBeLessThan(1)
  expect(Math.round(chart!.height)).toBe(width>650 ? 88 : 72)
  if (process.env.E2E_ARTIFACT_DIR) await page.screenshot({path:`${process.env.E2E_ARTIFACT_DIR}/기업상단_새배치_${width}.png`})
  await page.getByRole('button',{name:'내 계정',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'내 계정',exact:true})
  const inputs=dialog.locator('input')
  await inputs.nth(0).fill('current-password')
  await inputs.nth(1).fill('new-password-123')
  await inputs.nth(2).fill('different-password')
  await dialog.getByRole('button',{name:'비밀번호 변경',exact:true}).click()
  const toast=page.locator('[data-sonner-toast]').filter({hasText:'새 비밀번호가 일치하지 않습니다.'})
  await expect(toast).toBeVisible()
  await expect(dialog.locator('[data-sonner-toaster]')).toHaveCount(1)
  await expect(toast.locator('[data-close-button] svg')).toHaveCount(1)
  await expect(toast.locator('svg[class*="lucide-circle-alert"]')).toHaveCount(1)
  await expect.poll(async () => (await toast.boundingBox())!.y).toBeGreaterThanOrEqual(15)
  const box=await toast.boundingBox()
  expect(Math.abs(box!.x+box!.width/2-width/2)).toBeLessThan(2)
  expect(box!.y).toBeLessThanOrEqual(30)
  if (process.env.E2E_ARTIFACT_DIR) await page.screenshot({path:`${process.env.E2E_ARTIFACT_DIR}/계정_토스트_${width}.png`})
  await dialog.getByRole('button',{name:'내 계정 닫기',exact:true}).click()
 }
})
test('메모 추가와 삭제 및 서버 오류를 토스트로 표시하며 실제 서버 자료는 바꾸지 않습니다', async ({ page }) => {
 await page.goto('/companies/00126478?tab=memos')
 await expect(page.getByRole('button',{name:'메모 추가',exact:true})).toBeVisible()
 const row={id:'toast-preview',company_name:'삼성중공업',title:'토스트 검증 메모',current_version:1,created_at:'2026-10-21T00:00:00Z',updated_at:'2026-10-21T00:00:00Z'}
 await page.route('**/api/v1/memos/toast-preview/versions**', route => route.fulfill({json:new URL(route.request().url()).pathname.endsWith('/1') ? {version:1,content:'검증 메모',created_at:row.created_at} : [{version:1,created_at:row.created_at}]}))
 await page.route('**/api/v1/memos', route => route.request().method()==='POST' ? route.fulfill({status:201,json:row}) : route.continue())
 await page.route('**/api/v1/memos/toast-preview', route => route.fulfill({status:204}))
 await page.getByRole('button',{name:'메모 추가',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'메모 추가',exact:true})
 await dialog.getByRole('tab',{name:'작성',exact:true}).click()
 await dialog.getByRole('textbox',{name:'메모 내용',exact:true}).fill('검증 메모')
 await dialog.getByRole('button',{name:'저장',exact:true}).click()
 await expect(dialog.locator('[data-sonner-toast]').filter({hasText:'메모를 추가했습니다.'})).toBeVisible()
 await dialog.getByRole('button',{name:'메모 추가 닫기',exact:true}).click()
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'토스트 검증 메모 삭제',exact:true}).click()
 await expect(page.locator('[data-sonner-toast]').filter({hasText:'메모를 삭제했습니다.'})).toBeVisible()
 await page.route('**/api/v1/memos', route=>route.request().method()==='POST' ? route.fulfill({status:503,json:{error:{message:'검증 저장 오류'}}}) : route.continue())
 await page.getByRole('button',{name:'메모 추가',exact:true}).click()
 await dialog.getByRole('textbox',{name:'메모 내용',exact:true}).fill('검증 오류 메모')
 await dialog.getByRole('button',{name:'저장',exact:true}).click()
 const error=dialog.locator('[data-sonner-toast]').filter({hasText:'검증 저장 오류'})
 await expect(error).toBeVisible()
 await expect(error).toHaveCount(1)
})
