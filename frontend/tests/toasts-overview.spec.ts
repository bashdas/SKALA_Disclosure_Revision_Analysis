test('관심종목 해제 후 상세 시세를 유지하고 토스트 닫기는 오른쪽 위에 둡니다', async ({ page }) => {
  let selected = true
  await page.route('**/api/v1/favorites**', route => {
    if (route.request().method() === 'DELETE') {
      selected = false
      return route.fulfill({ status: 204 })
    }
    return route.fulfill({ json: selected ? [{ corp_code: '00126478', company_name: '삼성중공업', stock_code: '010140' }] : [] })
  })
  await page.goto('/companies/00126478')
  await expect(page.locator('.company-market-panel .skeleton-state')).toHaveCount(0)
  await expect(page.locator('.company-market-price strong')).not.toHaveText('시세 없음')
  const price = await page.locator('.company-market-price strong').textContent()
  await page.getByRole('button', { name: '삼성중공업 관심종목 해제', exact: true }).click()
  await expect(page.getByRole('button', { name: '삼성중공업 관심종목 추가', exact: true })).toBeVisible()
  await expect(page.locator('.company-market-name')).toContainText('010140')
  await expect(page.locator('.company-market-price strong')).toHaveText(price!)
  const toast = page.locator('[data-sonner-toast]').filter({ hasText: '관심종목에서 해제했습니다.' })
  await expect(toast).toBeVisible()
  await expect.poll(async () => (await toast.boundingBox())!.y).toBeGreaterThanOrEqual(15)
  const outer = await toast.boundingBox()
  const close = await toast.locator('[data-close-button]').boundingBox()
  expect(close!.x).toBeGreaterThan(outer!.x + outer!.width / 2)
  expect(Math.abs(outer!.x + outer!.width - close!.x - close!.width - 8)).toBeLessThan(2)
  expect(Math.abs(close!.y - outer!.y - 8)).toBeLessThan(2)
})
