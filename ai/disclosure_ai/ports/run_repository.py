from typing import Any, Protocol


class RunRepository(Protocol):
    db: Any
    lock: Any

    def row(self, task_id: str) -> dict: ...
    def begin(
        self, task_id: str, fingerprint: str, input_key: str = "", *, started=None
    ) -> None: ...
    def keep(self, task_id: str, key: str, value: dict) -> None: ...
    def event(self, task_id: str, kind: str, **payload) -> None: ...
    def cache(self, task_id, key, result, scope) -> None: ...
    def cached(self, task_id, key) -> dict | None: ...
    def lookup_state(self, task_id, key, tool, state, attempt=0) -> None: ...
