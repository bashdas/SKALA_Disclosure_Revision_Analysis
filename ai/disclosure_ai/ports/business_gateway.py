from typing import Protocol


class BusinessGateway(Protocol):
    async def call(self, name: str, args: dict) -> dict: ...
    async def ensure_active(self, task_id: str) -> dict: ...
    async def stage(self, task_id: str, stage: str) -> None: ...
    async def perspective(self, task_id: str, selection: dict, result=None) -> None: ...
